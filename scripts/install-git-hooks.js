#!/usr/bin/env node

/**
 * @file scripts/install-git-hooks.js
 * @description Installs deterministic Git hooks for the EOS control plane.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const gitHooksDir = path.join(rootDir, '.git', 'hooks');

export function installHooks(options = {}) {
  const targetDir = options.hooksDir || gitHooksDir;
  const filePath = options.preCommitPath || path.join(targetDir, 'pre-commit');
  const prePushPath = options.prePushPath || path.join(targetDir, 'pre-push');

  if (!fs.existsSync(targetDir)) {
    console.warn(`[WARN] Git hooks directory not found at: ${targetDir}`);
    return { success: false, reason: 'NO_GIT_DIR' };
  }

  const hookContent = `#!/bin/sh
# EOS Deterministic Pre-Commit Hook (Auto-generated by install-git-hooks.js)
node scripts/pre-commit-hook.js
`;

  const prePushContent = `#!/bin/sh
# EOS Local Main-Push Surrogate (Auto-generated by install-git-hooks.js)
# Fail-closed DENY of direct/force push to main unless EOS_ALLOW_MAIN_PUSH=1.
# LOCAL ONLY — not GitHub branch-protection enforcement.
node scripts/pre-push-hook.js
`;

  fs.writeFileSync(filePath, hookContent, { encoding: 'utf8', mode: 0o755 });
  fs.writeFileSync(prePushPath, prePushContent, { encoding: 'utf8', mode: 0o755 });
  // Also ensure chmod on systems supporting it
  try {
    fs.chmodSync(filePath, 0o755);
    fs.chmodSync(prePushPath, 0o755);
  } catch {
    // Ignore chmod error on Windows filesystems that do not support it
  }

  console.log(`✅ [EOS HARNESS]: Pre-commit hook installed at ${filePath}`);
  console.log(`✅ [EOS HARNESS]: Pre-push main-guard installed at ${prePushPath}`);
  return { success: true, path: filePath, paths: { preCommit: filePath, prePush: prePushPath } };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  installHooks();
}
