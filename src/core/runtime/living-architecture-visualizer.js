/**
 * EOS Living Architecture Visualizer & Mermaid C4 Engine
 * Generates interactive, deterministic C4 and Hexagonal component diagrams in Markdown format.
 */
export class LivingArchitectureVisualizer {
  /**
   * Generates a C4 System Context diagram using Mermaid syntax.
   * @param {object} [options]
   * @returns {string}
   */
  generateSystemContextMermaid(options = {}) {
    const systemName = options.systemName || 'EOS Autonomous SDLC';
    const description = options.description || 'Sovereign Engineering Control Plane';

    return `
graph TD
  User["Developer / Human Architect"] -->|Prompts & Commands| Cursor["Cursor IDE / Composer"]
  Cursor -->|JSON-RPC Tools| EOS["${systemName}<br/>(${description})"]
  EOS -->|Cryptographic Proofs| Ledger["Verified Evidence Ledger (docs/evidence)"]
  EOS -->|AST Pruning & Governance| TargetWorkspace["Target Codebase Workspaces"]

  classDef primary fill:#1e293b,stroke:#3b82f6,stroke-width:2px,color:#ffffff;
  classDef accent fill:#0f172a,stroke:#10b981,stroke-width:2px,color:#ffffff;
  class User,Cursor,EOS primary;
  class Ledger,TargetWorkspace accent;
`.trim();
  }

  /**
   * Generates a Hexagonal Component Architecture diagram in Mermaid syntax.
   * @param {object} layers
   * @param {string[]} [layers.domainModules]
   * @param {string[]} [layers.appModules]
   * @param {string[]} [layers.infraModules]
   * @param {string[]} [layers.presentationModules]
   * @returns {string}
   */
  generateHexagonalComponentsMermaid(layers = {}) {
    const domain = layers.domainModules || ['spec-drift-detector.js', 'cursor-tdd-auto-healer.js'];
    const app = layers.appModules || ['mission-orchestrator.js', 'parallel-auditor-dag.js'];
    const infra = layers.infraModules || ['mcp-router.js', 'heptaparaparshinokh-ledger.js'];
    const ui = layers.presentationModules || ['cursor-agent-orchestrator.mdc', 'slash-commands'];

    const domainNodes = domain.map((m, i) => `      D${i + 1}["${m}"]`).join('\n');
    const appNodes = app.map((m, i) => `      A${i + 1}["${m}"]`).join('\n');
    const infraNodes = infra.map((m, i) => `      I${i + 1}["${m}"]`).join('\n');
    const uiNodes = ui.map((m, i) => `      U${i + 1}["${m}"]`).join('\n');

    return `
graph TD
  subgraph Presentation_Layer["UI & Presentation Layer"]
${uiNodes}
  end

  subgraph Application_Layer["Application Layer (Use Cases & DAG)"]
${appNodes}
  end

  subgraph Pure_Domain_Layer["Pure Domain Layer (Zero Dependencies)"]
${domainNodes}
  end

  subgraph Infrastructure_Adapters["Infrastructure Adapters (I/O & Persistence)"]
${infraNodes}
  end

  Presentation_Layer --> Application_Layer
  Application_Layer --> Pure_Domain_Layer
  Infrastructure_Adapters --> Pure_Domain_Layer
  Application_Layer --> Infrastructure_Adapters
`.trim();
  }

  /**
   * Compiles complete visual architecture markdown document.
   * @param {object} [config]
   * @returns {string}
   */
  generateFullArchitectureMarkdown(config = {}) {
    const title = config.title || 'EOS System Master Architecture';
    const version = config.version || '0.4.0';

    const contextMermaid = this.generateSystemContextMermaid();
    const hexagonalMermaid = this.generateHexagonalComponentsMermaid();

    return `
# ${title} (v${version})

This document is automatically generated by the **EOS Living Architecture Visualizer**. It illustrates the system context and hexagonal component topology.

---

## 1. C4 System Context (Level 1)

\`\`\`mermaid
${contextMermaid}
\`\`\`

---

## 2. Clean / Hexagonal Layer Isolation (Level 3)

\`\`\`mermaid
${hexagonalMermaid}
\`\`\`

---

## 3. Inviolable Architectural Axioms
1. **Domain Purity**: Modules inside \`Pure_Domain_Layer\` MUST NOT import from \`Infrastructure_Adapters\` or UI frameworks.
2. **Deterministic Evidence**: All state transitions generate cryptographic receipts stored in \`docs/evidence/\`.
3. **Monotonic Governance**: No tool or subagent can elevate its own execution authority.
`.trim();
  }
}
